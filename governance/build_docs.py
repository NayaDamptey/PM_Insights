"""Generate the governance documents from the data dictionary, the extract config and
the DQ rules, so they always describe what the code actually does.

    .venv\\Scripts\\python governance\\build_docs.py

Writes governance/data_catalogue.md, lineage.md, pii.md and owners.md.
rls.md is written by hand.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from extract.build_config import DEFAULT_DICTIONARY  # noqa: E402
from fabric import silver_contract  # noqa: E402

HEADER = "<!-- Generated by governance/build_docs.py from the data dictionary; do not edit. -->\n\n"

# Personal and sensitive data, by Silver field. Each class maps to a proposed
# sensitivity label and how the field should be protected (see pii.md).
PII = {
    "Personal: identity": {
        "label": "Confidential - Personal",
        "fields": {
            "silver_tenant": ["title", "first_name", "last_name", "full_name"],
            "silver_applicant": ["first_name", "last_name"],
            "silver_staff": ["first_name", "last_name", "full_name"],
        },
    },
    "Personal: contact": {
        "label": "Confidential - Personal",
        "fields": {
            "silver_tenant": ["email", "mobile"],
            "silver_applicant": ["email", "mobile"],
            "silver_staff": ["email"],
            "silver_landlord": ["email", "phone"],
        },
    },
    "Personal: sensitive": {
        "label": "Highly Confidential - Personal",
        "fields": {"silver_tenant": ["right_to_rent_checked", "right_to_rent_check_date"]},
    },
    "Personal: financial": {
        "label": "Highly Confidential - Personal",
        "fields": {
            "silver_tenancy": ["closing_balance", "deposit_amount"],
            "silver_rent_transaction": ["amount", "reference"],
            "silver_applicant": ["max_budget"],
        },
    },
    "Bank details": {
        "label": "Highly Confidential - Financial",
        "fields": {
            "silver_landlord": ["bank_account_name", "bank_sort_code", "bank_account_number"]
        },
    },
    "Free text (may hold personal data)": {
        "label": "Confidential - Personal",
        "fields": {
            "silver_repair_job": ["feedback"],
            "silver_suspense_item": ["notes"],
        },
    },
}

PROTECTION = {
    "Personal: identity": "Shown to Head Office and Property Managers; hidden (OLS) for others",
    "Personal: contact": "Masked on SQL endpoint; hidden (OLS) except Head Office, PMs",
    "Personal: sensitive": "Masked everywhere; reported only as counts (checked yes/no)",
    "Personal: financial": "Row-level security: a user sees only the tenancies they manage",
    "Bank details": "Masked on the SQL endpoint; never in the semantic model",
    "Free text (may hold personal data)": "Not shown in reports; reviewed before any export",
}


def classification() -> dict[tuple[str, str], str]:
    return {
        (table, field): cls
        for cls, spec in PII.items()
        for table, fields in spec["fields"].items()
        for field in fields
    }


def load() -> tuple[pd.DataFrame, pd.DataFrame, dict, dict]:
    tables = pd.read_excel(DEFAULT_DICTIONARY, sheet_name="Tables", dtype=str)
    fields = pd.read_excel(DEFAULT_DICTIONARY, sheet_name="Fields", dtype=str)
    rules = yaml.safe_load((HERE / "dq_rules.yaml").read_text(encoding="utf-8"))
    config = yaml.safe_load((HERE.parent / "config" / "sources.yaml").read_text(encoding="utf-8"))
    return tables, fields, rules, config


def owners_by_table(rules: dict) -> dict[str, tuple[str, str, str]]:
    return {
        t: (domain, d["owner"], d["steward"])
        for domain, d in rules["domains"].items()
        for t in d["tables"]
    }


def cell(value: object) -> str:
    text = "" if pd.isna(value) else str(value)
    return text.replace("|", "\\|").replace("\n", " ")


def data_catalogue(tables: pd.DataFrame, fields: pd.DataFrame, rules: dict) -> str:
    contract = silver_contract.build()
    owners = owners_by_table(rules)
    pii = classification()
    silver_tables = tables[tables["Layer"] == "Silver"].set_index("Table")
    out = [
        "# Data catalogue: Silver layer (`ll_silver`)\n",
        HEADER,
        "Every Silver table and field, as defined in the data dictionary. "
        "**Classification** marks personal and sensitive data (see [pii.md](pii.md)).\n",
        "| Table | Domain | Owner | Description |",
        "|---|---|---|---|",
    ]
    for table in contract:
        domain, owner, _ = owners[table]
        out.append(
            f"| [{table}](#{table}) | {domain} | {owner} | "
            f"{cell(silver_tables.loc[table, 'Description'])} |"
        )
    for table, spec in contract.items():
        domain, owner, steward = owners[table]
        rows = fields[(fields["Layer"] == "Silver") & (fields["Table"] == table)]
        out += [
            f"\n## {table}\n",
            f"{cell(silver_tables.loc[table, 'Description'])}\n",
            f"- **Built from:** {spec['source_table']} ({spec['source_system']})",
            f"- **Key:** {', '.join(spec['key'])}",
            f"- **Domain:** {domain} · **Owner:** {owner} · **Steward:** {steward}\n",
            "| Field | Type | Key | Description | Source | Classification |",
            "|---|---|---|---|---|---|",
        ]
        for _, r in rows.iterrows():
            out.append(
                f"| {r['Field']} | {cell(r['Data type'])} | {cell(r['Key'])} | "
                f"{cell(r['Description'])} | {cell(r['API endpoint / source field'])} | "
                f"{pii.get((table, r['Field']), '')} |"
            )
    return "\n".join(out) + "\n"


def lineage(config: dict) -> str:
    contract = silver_contract.build()
    systems = {"qube": "MRI Qube PM", "fixflo": "FixFlo", "engage": "MRI Engage CRM"}
    out = [
        "# Lineage\n",
        HEADER,
        "## Layers\n",
        "```mermaid",
        "flowchart LR",
        '  api["Source APIs<br/>MRI Qube PM · FixFlo · MRI Engage CRM"]',
        '  csv["data/landing/csv<br/>extract.run"]',
        '  bronze["ll_bronze<br/>raw text + lineage columns<br/>01_bronze"]',
        '  silver["ll_silver<br/>typed, conformed<br/>02_silver"]',
        '  dq["dq_results / dq_exceptions<br/>03_dq"]',
        '  gold["ll_gold<br/>star schema<br/>04_gold"]',
        '  pbi["Semantic model +<br/>Power BI report"]',
        "  api --> csv --> bronze --> silver --> gold --> pbi",
        "  silver --> dq",
        "```\n",
        "## Bronze → Silver, by table\n",
        "```mermaid",
        "flowchart LR",
    ]
    bronze_used = sorted(
        {b.strip() for spec in contract.values() for b in spec["source_table"].split(",")}
    )
    for prefix, name in systems.items():
        members = [b for b in bronze_used if b.startswith(prefix + "_")]
        out.append(f'  subgraph {prefix}["{name}"]')
        out += [f"    {b}" for b in members]
        out.append("  end")
    out.append('  subgraph ref["Generated in Fabric"]\n    dim_calendar\n  end')
    for table, spec in contract.items():
        for b in spec["source_table"].split(","):
            out.append(f"  {b.strip()} --> {table}")
    out += [
        "```\n",
        "## Source endpoint → Bronze → Silver\n",
        "| Source endpoint | Bronze table | Silver table(s) |",
        "|---|---|---|",
    ]
    used_by: dict[str, list[str]] = {}
    for table, spec in contract.items():
        for b in spec["source_table"].split(","):
            used_by.setdefault(b.strip(), []).append(table)
    for b, t in config["tables"].items():
        out.append(
            f"| {cell(t['source_endpoint'])} | {b} | {', '.join(used_by.get(b, [])) or '–'} |"
        )
    out.append(
        "\nEvery Bronze row carries `_source_file`, `_run_id`, `_ingested_at` and "
        "`_source_system`; every Silver row carries `source_system`, `source_table` and "
        "`loaded_at`, so any reported figure can be traced back to the load and file it "
        "came from.\n"
    )
    return "\n".join(out)


def pii_doc() -> str:
    out = [
        "# Personal and sensitive data\n",
        HEADER,
        "Classification of Silver fields that hold personal or sensitive data, with the "
        "proposed Microsoft Purview sensitivity label and how each is protected. The same "
        "classification appears in [data_catalogue.md](data_catalogue.md).\n",
        "| Class | Label | Protection |",
        "|---|---|---|",
    ]
    for cls, spec in PII.items():
        out.append(f"| {cls} | {spec['label']} | {PROTECTION[cls]} |")
    out += ["\n## Fields\n", "| Table | Field | Class |", "|---|---|---|"]
    for (table, field), cls in sorted(classification().items()):
        out.append(f"| {table} | {field} | {cls} |")
    out += [
        "\n## How the protection is applied\n",
        "- **Sensitivity labels.** Apply the labels above in Microsoft Purview to "
        "`ll_silver`, `ll_gold` and the semantic model, so they follow the data into "
        "exports (Excel, PDF) and block unlabelled sharing.",
        "- **Masking on the SQL endpoint.** Dynamic data masking on the Gold tables' "
        "contact and bank fields, e.g. `ALTER TABLE ... ALTER COLUMN email ADD MASKED "
        "WITH (FUNCTION = 'email()')`; only roles granted `UNMASK` see real values.",
        "- **Object-level security (OLS).** In the semantic model, tenant names, emails, "
        "mobiles and bank details are hidden from every role except Head Office and "
        "Property Manager.",
        "- **Row-level security.** Tenancy balances and rent transactions are filtered to "
        "the homes a user manages (see [rls.md](rls.md)).",
        "- **Lakehouse access.** Only data engineers can read `ll_bronze` and "
        "`ll_silver`; analysts and report users get `ll_gold` and the semantic model.",
        "- **Retention.** Personal data of former tenants and unsuccessful applicants "
        "should be reviewed against the retention policy (e.g. 6 years after the "
        "tenancy ends) and removed in the source systems.",
    ]
    return "\n".join(out) + "\n"


def owners_doc(rules: dict) -> str:
    out = [
        "# Data owners and stewards\n",
        HEADER,
        "Each Silver table belongs to one domain. The **owner** is accountable for the "
        "data and decides what “correct” means; the **steward** works the DQ exceptions "
        "and gets them fixed in the source system.\n",
        "| Domain | Owner | Steward | Tables |",
        "|---|---|---|---|",
    ]
    for domain, d in rules["domains"].items():
        out.append(f"| {domain} | {d['owner']} | {d['steward']} | {', '.join(d['tables'])} |")
    counts: dict[str, int] = {}
    for r in rules["rules"]:
        counts[r["owner"]] = counts.get(r["owner"], 0) + 1
    out += [
        "\n## Rules per owner\n",
        "| Owner | Rules |",
        "|---|---|",
    ]
    out += [f"| {o} | {n} |" for o, n in sorted(counts.items(), key=lambda x: -x[1])]
    out += [
        "\n“table owner” rules (keys, links, types, freshness) run on every table and go "
        "to that table's owner.\n",
        "## How a data quality issue is handled\n",
        "1. `03_dq` runs after each Silver load and writes `dq_results` and " "`dq_exceptions`.",
        "2. The steward filters `dq_exceptions` to their domain, highest severity first.",
        "3. The record is corrected **in the source system** (Qube, FixFlo or Engage), "
        "never in the lakehouse, so the next load brings the fix through.",
        "4. The next DQ run shows the failure count going down; the trend is reported on "
        "the Data Quality page of the report.",
        "5. A rule that is wrong (not the data) is changed in `governance/dq_rules.yaml` "
        "with the owner's agreement.",
    ]
    return "\n".join(out) + "\n"


def documents() -> dict[str, str]:
    tables, fields, rules, config = load()
    return {
        "data_catalogue.md": data_catalogue(tables, fields, rules),
        "lineage.md": lineage(config),
        "pii.md": pii_doc(),
        "owners.md": owners_doc(rules),
    }


def main() -> None:
    for name, text in documents().items():
        (HERE / name).write_text(text, encoding="utf-8")
        print("wrote", HERE / name)


if __name__ == "__main__":
    main()
