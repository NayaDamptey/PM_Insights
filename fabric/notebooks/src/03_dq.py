from pyspark.sql import types as T

for ddl in (
    f"""CREATE TABLE IF NOT EXISTS {db}.dq_results (
            run_id STRING, rule_id STRING, rule_name STRING, dimension STRING,
            severity STRING, owner STRING, table_name STRING, column_name STRING,
            records_checked BIGINT, failures BIGINT, failure_pct DOUBLE, result STRING,
            sample_failing_keys STRING, error STRING, checked_at TIMESTAMP) USING DELTA""",
    f"""CREATE TABLE IF NOT EXISTS {db}.dq_exceptions (
            run_id STRING, rule_id STRING, rule_name STRING, dimension STRING,
            severity STRING, owner STRING, table_name STRING, record_key STRING,
            column_name STRING, detail STRING, checked_at TIMESTAMP) USING DELTA""",
):
    spark.sql(ddl)
# Re-running the same run_id replaces its rows.
spark.sql(f"DELETE FROM {db}.dq_results WHERE run_id = '{run_id}'")
spark.sql(f"DELETE FROM {db}.dq_exceptions WHERE run_id = '{run_id}'")

results = []
for rule in DQ_RULES["rules"]:
    for chk in checks_for(rule):
        owner = TABLE_OWNER.get(chk["table"]) if rule["owner"] == "table owner" else rule["owner"]
        row = {
            "run_id": run_id,
            "rule_id": rule["id"],
            "rule_name": rule["name"],
            "dimension": rule["dimension"],
            "severity": rule["severity"],
            "owner": owner,
            "table_name": chk["table"],
            "column_name": chk["column"],
            "checked_at": checked_at,
        }
        try:
            failing = spark.sql(chk["failing"])
            failing.createOrReplaceTempView("failing_rows")
            spark.sql(f"""
                INSERT INTO {db}.dq_exceptions
                SELECT {literal(run_id)}, {literal(rule["id"])}, {literal(rule["name"])},
                       {literal(rule["dimension"])}, {literal(rule["severity"])},
                       {literal(owner)}, {literal(chk["table"])},
                       record_key, column_name, detail, TIMESTAMP '{checked_at}'
                FROM failing_rows
            """)
            failures = spark.table("failing_rows").count()
            checked = spark.sql(chk["checked"]).first()[0]
            sample = [r[0] for r in failing.select("record_key").limit(10).collect()]
            row.update(
                records_checked=checked,
                failures=failures,
                failure_pct=round(100 * failures / checked, 3) if checked else 0.0,
                result="PASS" if failures == 0 else "FAIL",
                sample_failing_keys=", ".join(str(k) for k in sample) or None,
                error=None,
            )
        except Exception as exc:  # noqa: BLE001 - a broken rule must not stop the others
            row.update(
                records_checked=None,
                failures=None,
                failure_pct=None,
                result="ERROR",
                sample_failing_keys=None,
                error=str(exc)[:1000],
            )
        results.append(row)

RESULT_SCHEMA = spark.table(f"{db}.dq_results").schema
spark.createDataFrame(
    [tuple(r[f.name] for f in RESULT_SCHEMA.fields) for r in results], RESULT_SCHEMA
).write.mode("append").saveAsTable(f"{db}.dq_results")

