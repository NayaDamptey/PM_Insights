# ## Null profile
# How many values are blank in every Silver column. Not a pass/fail rule: it shows where
# the data is thin, so the owners can decide which fields must be filled.

# %%
profile_rows = []
for table, spec in SILVER_CONTRACT.items():
    cols = [c for c, _ in spec["columns"]]
    counts = spark.sql(
        "SELECT COUNT(*) AS total_rows, "
        + ", ".join(
            f"SUM(CASE WHEN {q(c)} IS NULL OR trim(CAST({q(c)} AS STRING)) = '' "
            f"THEN 1 ELSE 0 END) AS {q(c)}"
            for c in cols
        )
        + f" FROM {db}.{table}"
    ).first()
    total = counts["total_rows"]
    for c in cols:
        blank = counts[c] or 0
        profile_rows.append(
            (run_id, table, c, total, blank, round(100 * blank / total, 2) if total else 0.0)
        )

PROFILE_SCHEMA = T.StructType(
    [
        T.StructField("run_id", T.StringType()),
        T.StructField("table_name", T.StringType()),
        T.StructField("column_name", T.StringType()),
        T.StructField("total_rows", T.LongType()),
        T.StructField("blank_values", T.LongType()),
        T.StructField("blank_pct", T.DoubleType()),
    ]
)
spark.sql(
    f"CREATE TABLE IF NOT EXISTS {db}.dq_null_profile ("
    "run_id STRING, table_name STRING, column_name STRING, total_rows BIGINT, "
    "blank_values BIGINT, blank_pct DOUBLE) USING DELTA"
)
spark.sql(f"DELETE FROM {db}.dq_null_profile WHERE run_id = '{run_id}'")
spark.createDataFrame(profile_rows, PROFILE_SCHEMA).write.mode("append").saveAsTable(
    f"{db}.dq_null_profile"
)

