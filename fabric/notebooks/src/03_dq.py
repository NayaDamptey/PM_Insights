# %% [markdown]
# ## Turning rules into SQL
# Every check becomes two queries on one Silver table: one that returns the failing rows
# (`record_key`, `column_name`, `detail`) and one that counts the records checked.

# %%
from datetime import UTC, datetime

checked_at = datetime.now(UTC).replace(tzinfo=None)
run_id = run_id or f"DQ{checked_at:%Y%m%dT%H%M%S}"
db = silver_db

TABLE_OWNER = {
    table: domain["owner"] for domain in DQ_RULES["domains"].values() for table in domain["tables"]
}


def q(name: str) -> str:
    return f"`{name}`"


def literal(text: str) -> str:
    """A Spark SQL string literal (backslashes and quotes escaped)."""
    return "'" + str(text).replace("\\", "\\\\").replace("'", "\\'") + "'"


def record_key(table: str, alias: str = "") -> str:
    prefix = f"{alias}." if alias else ""
    cols = ", ".join(f"CAST({prefix}{q(k)} AS STRING)" for k in SILVER_CONTRACT[table]["key"])
    return f"concat_ws('|', {cols})"


def checks_for(rule: dict) -> list[dict]:
    """One entry per table/column the rule looks at: {table, column, failing, checked}."""
    check, t = rule["check"], rule["table"]
    tables = list(SILVER_CONTRACT) if t == "all" else [t]
    out = []

    if check == "primary_key":
        for table in tables:
            key = SILVER_CONTRACT[table]["key"]
            blank = " OR ".join(f"{q(k)} IS NULL" for k in key)
            out.append(
                {
                    "table": table,
                    "column": ", ".join(key),
                    "failing": f"""
                        SELECT {record_key(table)} AS record_key, {literal(", ".join(key))} AS column_name,
                               CASE WHEN {blank} THEN 'key is blank'
                                    ELSE concat('key appears ', n, ' times') END AS detail
                        FROM (SELECT *, COUNT(*) OVER (PARTITION BY {", ".join(q(k) for k in key)}) AS n
                              FROM {db}.{table}) x
                        WHERE n > 1 OR {blank}""",
                    "checked": f"SELECT COUNT(*) FROM {db}.{table}",
                }
            )

    elif check == "foreign_key":
        for table in tables:
            for column, ref in SILVER_CONTRACT[table]["foreign_keys"]:
                ref_key = SILVER_CONTRACT[ref]["key"][0]
                out.append(
                    {
                        "table": table,
                        "column": column,
                        "failing": f"""
                            SELECT {record_key(table, "c")} AS record_key, '{column}' AS column_name,
                                   concat('{column} ', c.{q(column)}, ' not found in {ref}') AS detail
                            FROM {db}.{table} c
                            LEFT ANTI JOIN {db}.{ref} r ON r.{q(ref_key)} = c.{q(column)}
                            WHERE c.{q(column)} IS NOT NULL""",
                        "checked": f"SELECT COUNT(*) FROM {db}.{table} WHERE {q(column)} IS NOT NULL",
                    }
                )

    elif check == "type_converts":
        # Silver logs every value it couldn't convert; only the table's latest load counts.
        for table in tables:
            out.append(
                {
                    "table": table,
                    "column": "typed columns",
                    "failing": f"""
                        SELECT record_key, column_name,
                               concat("'", raw_value, "' is not a valid ", target_type) AS detail
                        FROM {db}._cast_errors
                        WHERE table_name = '{table}'
                          AND loaded_at = (SELECT max(loaded_at) FROM {db}.{table})""",
                    "checked": f"SELECT COUNT(*) FROM {db}.{table}",
                }
            )

    elif check == "not_null":
        cols = rule["columns"]
        out.append(
            {
                "table": t,
                "column": ", ".join(cols),
                "failing": " UNION ALL ".join(
                    f"""SELECT {record_key(t)} AS record_key, '{c}' AS column_name,
                               '{c} is blank' AS detail
                        FROM {db}.{t}
                        WHERE {q(c)} IS NULL OR trim(CAST({q(c)} AS STRING)) = ''""" for c in cols
                ),
                "checked": f"SELECT COUNT(*) * {len(cols)} FROM {db}.{t}",
            }
        )

    elif check in ("pattern", "allowed_values", "range"):
        c = rule["column"]
        if check == "pattern":
            bad = f"NOT ({q(c)} RLIKE {literal(rule['regex'])})"
            why = f'concat("\'", {q(c)}, "\' is not in the expected format")'
        elif check == "allowed_values":
            bad = f"{q(c)} NOT IN ({', '.join(literal(v) for v in rule['values'])})"
            why = f'concat("\'", {q(c)}, "\' is not an allowed value")'
        else:
            bad = f"({q(c)} < {rule['min']} OR {q(c)} > {rule['max']})"
            why = f"concat({q(c)}, ' is outside {rule['min']} to {rule['max']}')"
        out.append(
            {
                "table": t,
                "column": c,
                "failing": f"""
                    SELECT {record_key(t)} AS record_key, '{c}' AS column_name, {why} AS detail
                    FROM {db}.{t}
                    WHERE {q(c)} IS NOT NULL AND {bad}""",
                "checked": f"SELECT COUNT(*) FROM {db}.{t} WHERE {q(c)} IS NOT NULL",
            }
        )

    elif check == "date_window":
        for c in rule["columns"]:
            out.append(
                {
                    "table": t,
                    "column": c,
                    "failing": f"""
                        SELECT {record_key(t)} AS record_key, '{c}' AS column_name,
                               concat('{c} ', {q(c)}, ' is before {rule['min']} or in the future')
                                   AS detail
                        FROM {db}.{t}
                        WHERE CAST({q(c)} AS DATE) < DATE '{rule['min']}'
                           OR CAST({q(c)} AS DATE) > current_date()""",
                    "checked": f"SELECT COUNT(*) FROM {db}.{t} WHERE {q(c)} IS NOT NULL",
                }
            )

    elif check == "freshness":
        c, hours = rule["column"], rule["max_age_hours"]
        for table in tables:
            out.append(
                {
                    "table": table,
                    "column": c,
                    "failing": f"""
                        SELECT '{table}' AS record_key, '{c}' AS column_name,
                               concat('newest {c} is ', coalesce(CAST(newest AS STRING), 'missing'),
                                      ', more than {hours} hours ago') AS detail
                        FROM (SELECT max(CAST({q(c)} AS TIMESTAMP)) AS newest FROM {db}.{table}) x
                        WHERE newest IS NULL
                           OR newest < current_timestamp() - INTERVAL {hours} HOURS""",
                    "checked": "SELECT 1",
                }
            )

    elif check == "sql":
        out.append(
            {
                "table": t,
                "column": rule["column"],
                "failing": rule["sql"].format(db=db),
                "checked": rule.get("checked_sql", f"SELECT COUNT(*) FROM {{db}}.{t}").format(
                    db=db
                ),
            }
        )

    else:
        raise ValueError(f"{rule['id']}: unknown check {check!r}")
    return out


